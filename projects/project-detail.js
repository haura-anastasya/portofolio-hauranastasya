const key = document.body.dataset.project;
const project = projects[key];
const el = id => document.getElementById(id);
const esc = s => s.replace(/[&<>"]/g, c => ({'&':'&amp;','<':'&lt;','>':'&gt;','"':'&quot;'}[c]));

if (project) {
  document.title = `${project.title} | Haura Anastasya`;
  el('projectTitle').textContent = project.title;
  el('projectCategory').textContent = project.category;
  el('projectDescription').textContent = project.description;

  const total = project.groups.reduce((n, g) => n + g.items.length, 0);
  el('projectCount').textContent = `${total} Projects`;

  const list = el('videoList');
  let n = 0;
  project.groups.forEach(group => {
    if (group.heading) {
      const h = document.createElement('h3');
      h.className = 'group-heading';
      h.textContent = group.heading;
      list.appendChild(h);
    }
    const grid = document.createElement('div');
    grid.className = 'video-grid';
    group.items.forEach(item => {
      n++;
      const platform = item.url.includes('instagram.com') ? 'Instagram' : 'TikTok';
      const a = document.createElement('a');
      a.className = 'video-card';
      a.href = item.url; a.target = '_blank'; a.rel = 'noopener noreferrer';
      a.innerHTML =
        `<span class="video-number">${String(n).padStart(2, '0')} · ${platform.toUpperCase()}</span>` +
        `<strong>${esc(item.title)}</strong>` +
        `<span class="video-cat">${esc(item.category)}</span>` +
        (item.roles ? `<small>${esc(item.roles)}</small>` : '') +
        `<span class="video-cta">View on ${platform} ↗</span>`;
      grid.appendChild(a);
    });
    list.appendChild(grid);
  });
}
const year = el('year');
if (year) year.textContent = new Date().getFullYear();

// Reveal animation + scroll progress (these pages don't load script.js)
document.querySelectorAll('.reveal').forEach(e => e.classList.add('show'));
const bar = document.getElementById('scrollProgress');
if (bar) {
  const upd = () => {
    const h = document.documentElement.scrollHeight - window.innerHeight;
    bar.style.width = (h > 0 ? (window.scrollY / h) * 100 : 0) + '%';
  };
  window.addEventListener('scroll', upd, { passive: true });
  upd();
}
